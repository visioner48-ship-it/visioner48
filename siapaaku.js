/* =====================================================
   VARIABEL GAME
   ===================================================== */

let soalGame = [];
let soalSekarang = 0;
let skor = 0;
let sudahMenjawab = false;


/* =====================================================
   ACAK SOAL
   ===================================================== */

function acakArray(array) {

    let hasil = [...array];

    for (let i = hasil.length - 1; i > 0; i--) {

        let j = Math.floor(Math.random() * (i + 1));

        [hasil[i], hasil[j]] =
        [hasil[j], hasil[i]];
    }

    return hasil;
}


/* =====================================================
   MULAI GAME
   ===================================================== */

function mulaiGame() {

    soalSekarang = 0;
    skor = 0;
    sudahMenjawab = false;

    // Acak 25 soal
    let soalAcak = acakArray(semuaSoal);

    // Ambil 5 soal
    soalGame = soalAcak.slice(0, 5);

    document.getElementById("game").style.display = "block";

    document.getElementById("hasil").style.display = "none";

    tampilkanSoal();
}


/* =====================================================
   TAMPILKAN SOAL
   ===================================================== */

function tampilkanSoal() {

    sudahMenjawab = false;

    let data = soalGame[soalSekarang];

    document.getElementById("nomor-soal").innerText =
        "Soal " + (soalSekarang + 1) + " dari 5";

    document.getElementById("soal").innerText =
        data.soal;

    let pilihan =
        document.getElementById("pilihan");

    pilihan.innerHTML = "";


    data.pilihan.forEach(function(item) {

        let tombol =
            document.createElement("button");

        tombol.className =
            "pilihan-jawaban";

        tombol.innerText =
            item;

        tombol.onclick = function() {

            pilihJawaban(
                item.charAt(0)
            );

        };

        pilihan.appendChild(tombol);

    });
}


/* =====================================================
   CEK JAWABAN
   ===================================================== */

function pilihJawaban(jawaban) {

    if (sudahMenjawab) {
        return;
    }

    sudahMenjawab = true;

    let data =
        soalGame[soalSekarang];

    let tombol =
        document.querySelectorAll(
            ".pilihan-jawaban"
        );


    tombol.forEach(function(btn) {

        btn.disabled = true;

        let huruf =
            btn.innerText.charAt(0);


        // Jawaban benar
        if (huruf === data.jawaban) {

            btn.classList.add("benar");

        }


        // Jawaban yang dipilih salah
        if (
            huruf === jawaban &&
            jawaban !== data.jawaban
        ) {

            btn.classList.add("salah");

        }

    });


    // Tambah skor jika benar
    if (jawaban === data.jawaban) {

        skor++;

    }


    // Lanjut setelah 0,7 detik
    setTimeout(function() {

        soalSekarang++;


        if (soalSekarang < 5) {

            tampilkanSoal();

        } else {

            tampilkanHasil();

        }

    }, 700);
}


/* =====================================================
   HASIL
   ===================================================== */

function tampilkanHasil() {

    document.getElementById("game").style.display =
        "none";

    document.getElementById("hasil").style.display =
        "block";


    document.getElementById("nilai").innerText =
        skor + " / 5";


    let pesan;


    if (skor === 5) {

        pesan =
            "Sempurna! Kamu benar semua!";

    } else if (skor >= 4) {

        pesan =
            "Hebat! Pengetahuan 48 Group kamu keren!";

    } else if (skor >= 3) {

        pesan =
            "Bagus! Tinggal sedikit lagi untuk sempurna.";

    } else if (skor >= 1) {

        pesan =
            "Lumayan! Coba Main Lagi.";

    } else {

        pesan =
            "Belum berhasil. Jangan menyerah!";

    }


    document.getElementById("pesan").innerText =
        pesan;
}


/* =====================================================
   MAIN LAGI
   ===================================================== */

function mainLagi() {

    /*
       Mengacak kembali 25 soal
       lalu mengambil 5 soal baru.
    */

    mulaiGame();
}


